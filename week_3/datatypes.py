
#we want to discuss all the data types in python
#string data type
name = "Musa"
print(name)

#integer data type
age = 20
print(age)

#float data type
height = 5.9
print(height)

#boolean data type
is_adult = True
print(is_adult)

#list data type
fruits = ["apple", "banana", "cherry"]
print(fruits)

#tuple data type
coordinates = (10.0, 20.0)
print(coordinates)

#dictionary data type
person = {"name": "Musa", "age": 20}
print(person)

#set data type
unique_numbers = {1, 2, 3, 4, 5, 5, 4, 3}
print(unique_numbers)

#none data type
nothing = None
print(nothing)

my_list = [1, "Hello", 3.14, True, [1, 2, 3]]
print(my_list)